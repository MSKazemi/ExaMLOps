def test_socket_proxies_grant_only_what_their_client_needs():
    """tecnativa's POST switch applies to every allowed section, so a proxy that may POST must
    not allow networks, images, exec or volumes; and each proxy lists every section explicitly."""
    services = _services()
    sections = {
        "CONTAINERS",
        "NETWORKS",
        "POST",
        "IMAGES",
        "VOLUMES",
        "EXEC",
        "INFO",
        "AUTH",
        "SECRETS",
        "SWARM",
        "SERVICES",
        "TASKS",
        "BUILD",
        "COMMIT",
        "CONFIGS",
        "DISTRIBUTION",
        "NODES",
        "PLUGINS",
        "SYSTEM",
    }
    for name in SOCKET_PROXIES:
        env = services[name]["environment"]
        assert sections <= set(env), f"{name} leaves {sorted(sections - set(env))} to defaults"
        if env["POST"] == "1":
            for risky in ("NETWORKS", "IMAGES", "EXEC", "VOLUMES", "BUILD", "SYSTEM"):
                assert env[risky] == "0", f"{name} may POST and allows {risky}"
    assert services["logs-proxy"]["environment"]["POST"] == "0"
    assert services["logs-proxy"].get("profiles") == ["monitoring"]


