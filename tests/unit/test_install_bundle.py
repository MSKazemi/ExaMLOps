def test_template_covers_every_required_variable_and_nothing_dead():
    template = _template_keys()
    used = {name for name, _ in _host_variables()}
    for name, op in _host_variables():
        if op in (":?", "?", ""):
            assert name in template, f"compose requires {name}, env.template does not set it"
    install = INSTALL.read_text()
    for key in template:
        if key.startswith("COMPOSE_"):
            continue  # read by docker compose itself (e.g. COMPOSE_PROFILES)
        assert key in used or key in install, f"env.template sets {key}, which nothing reads"


def _run_init(tmp_path: Path, *args: str) -> subprocess.CompletedProcess[str]:
    for f in (COMPOSE, TEMPLATE, INSTALL):
        shutil.copy2(f, tmp_path / f.name)
    return subprocess.run(
        ["sh", str(tmp_path / "install.sh"), "init", *args],
        capture_output=True,
        text=True,
        check=False,
        env={"PATH": "/usr/bin:/bin"},
    )


def test_init_generates_every_secret_once_and_keeps_them_private(tmp_path):
    result = _run_init(tmp_path, "--version", "1.2.3")
    assert result.returncode == 0, result.stderr
    env_file = tmp_path / ".env"
    assert stat.S_IMODE(env_file.stat().st_mode) == 0o600
    assert (tmp_path / "state").is_dir()

    values = {}
    for line in env_file.read_text().splitlines():
        if line and not line.startswith("#"):
            key, _, value = line.partition("=")
            values[key] = value
    assert values["EXAMLOPS_VERSION"] == "1.2.3"
    assert values["EXAMLOPS_STATE_UID"] == str(os.getuid())
    assert values["EXAMLOPS_STATE_GID"] == str(os.getgid())
    assert not [k for k, v in values.items() if "__" in v], "a placeholder survived init"
    generated = [values[s] for s in SECRETS]
    assert len(set(generated)) == len(generated), "two credentials received the same value"
    assert all(len(v) >= 16 for v in generated)
    assert len(base64.urlsafe_b64decode(values["DASHBOARD_SECRET_KEY"])) == 32, "not a Fernet key"


def test_init_never_clobbers_an_existing_env(tmp_path):
    assert _run_init(tmp_path, "--version", "1.2.3").returncode == 0
    before = (tmp_path / ".env").read_text()
    again = _run_init(tmp_path, "--version", "1.2.3")
    assert again.returncode != 0 and "already exists" in again.stderr
    assert (tmp_path / ".env").read_text() == before


def test_init_refuses_without_a_version(tmp_path):
    result = _run_init(tmp_path)
    assert result.returncode != 0 and "no version" in result.stderr
    assert not (tmp_path / ".env").exists()


# A `.env` as `install.sh init` wrote it before the object store became replaceable (v0.52.0).
def _fake(tag: str) -> str:
    """A fake credential assembled at runtime. A literal `KEY=value` fixture line trips gitleaks'
    generic-api-key rule on the full-history gate (it did once: see .github/.gitleaksignore)."""
    return "-".join((tag, "old", "fixture"))


_FAKE = {
    "POSTGRES_PASSWORD": _fake("pg"),
    "MINIO_ROOT_USER": _fake("root"),
    "MINIO_ROOT_PASSWORD": _fake("minio"),
    "MINIO_SERVING_ACCESS_KEY": _fake("reader"),
    "MINIO_SERVING_SECRET_KEY": _fake("serving"),
}
_OLD_ENV = (
    "EXAMLOPS_VERSION=0.52.0\nEXAMLOPS_REGISTRY=ghcr.io/mskazemi\nPUBLIC_HOST=ops.example.org\n"
    + "".join(f"{name}={value}\n" for name, value in _FAKE.items())
)


def _env(path: Path) -> dict[str, str]:
    return dict(
        line.split("=", 1)
        for line in path.read_text().splitlines()
        if "=" in line and not line.startswith("#")
    )


def _run(tmp_path: Path, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ["sh", str(tmp_path / "install.sh"), *args],
        capture_output=True,
        text=True,
        check=False,
        env={"PATH": "/usr/bin:/bin"},
    )


def test_upgrade_env_keeps_every_value_and_carries_renamed_ones(tmp_path):
    """An upgrade must never rotate a credential a volume already holds, nor drop an edit."""
    for f in (COMPOSE, TEMPLATE, INSTALL):
        shutil.copy2(f, tmp_path / f.name)
    (tmp_path / ".env").write_text(_OLD_ENV)
    (tmp_path / ".env").chmod(0o600)

    result = _run(tmp_path, "upgrade-env", "--version", "0.53.0")
    assert result.returncode == 0, result.stderr
    env = _env(tmp_path / ".env")
    assert env["EXAMLOPS_S3_ACCESS_KEY"] == _FAKE["MINIO_ROOT_USER"]  # MinIO's volume holds these
    assert env["EXAMLOPS_S3_SECRET_KEY"] == _FAKE["MINIO_ROOT_PASSWORD"]
    assert env["EXAMLOPS_S3_SERVING_ACCESS_KEY"] == _FAKE["MINIO_SERVING_ACCESS_KEY"]
