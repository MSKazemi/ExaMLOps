def _release_bundle_entries() -> set[str]:
    """Top-level names the release job copies into the bundle tarball."""
    workflow = yaml.safe_load(RELEASE.read_text())
    run = "\n".join(s.get("run", "") for s in workflow["jobs"]["github-release"]["steps"])
    listed = re.search(r"install/\{([^}]+)\}", run)
    assert listed, "the release no longer assembles the compose bundle"
    return set(listed.group(1).split(","))


def test_every_file_the_bundle_mounts_ships_with_the_release():
    entries = _release_bundle_entries()
    for name, svc in _services().items():
        for volume in svc.get("volumes", []):
            if volume.startswith("./") and not volume.startswith("./secrets/"):
                top = volume[2:].split("/", 1)[0]
                assert top in entries, f"{name} mounts {volume!r}; the release tarball omits {top}"
                assert (BUNDLE / volume[2:].split(":", 1)[0]).exists(), f"{name}: {volume!r}"


def test_secrets_can_never_ship_in_the_tarball():
    """The release dereferences ./monitoring into a public tarball; secrets live elsewhere.

    Alertmanager's receiver secrets sit in ./secrets (created by install.sh, gitignored, not in
    the release list), and everything reachable under ./monitoring — symlinks followed — must
    be a tracked file, so a bundle built from a working tree carries nothing a site wrote.
    """
    assert not any(
        e.startswith("secrets") or e in (".env", "state") for e in _release_bundle_entries()
    )
    assert "mkdir -p secrets/alertmanager" in INSTALL.read_text()
    tracked = set(
        subprocess.run(
            ["git", "ls-files", "platform/infra/docker-compose"],
            cwd=REPO,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.split()
    )
    reached = []
    for root, _dirs, files in os.walk(MONITORING, followlinks=True):
        for f in files:
            path = (Path(root) / f).resolve().relative_to(REPO).as_posix()
            reached.append(path)
            assert path in tracked or path in BUNDLE_OWN_MONITORING, (
                f"{path} would ship in the release tarball but is not tracked by git"
            )
    assert reached, "nothing under install/monitoring"


def test_shared_monitoring_config_is_linked_not_copied():
    """One source of truth: the shared configs are symlinks into the development stack's files.

    Grafana's provisioning is a directory symlink, deliberately: Docker resolves a mount *source*
    on the host, but symlinks *inside* a mounted directory resolve inside the container, where
    the development tree does not exist, so per-file links there leave Grafana empty when the
    bundle runs from a checkout. The release tarball dereferences them all (`cp -rL`).
    """
    shared = (
        "alert_rules.yml",
        "alertmanager.yml",
        "loki-config.yml",
        "tempo-config.yml",
        "grafana",
    )
    for name in shared:
        link = MONITORING / name
        assert link.is_symlink(), f"monitoring/{name} must link to the development stack's copy"
        assert link.resolve() == (BUNDLE.parent / name).resolve(), f"monitoring/{name}"


def test_bundle_prometheus_keeps_only_jobs_it_runs_and_copies_them_verbatim():
    """A job whose target is absent keeps `up == 0` firing TargetDown forever."""
    bundle = {
        j["job_name"]: j
        for j in yaml.safe_load((MONITORING / "prometheus.yml").read_text())["scrape_configs"]
    }
    dev = {j["job_name"]: j for j in yaml.safe_load(DEV_PROMETHEUS.read_text())["scrape_configs"]}
    services = set(_services())
    for job, spec in bundle.items():
        assert spec == dev.get(job), f"job {job!r} differs from ../prometheus.yml"
    for job, spec in dev.items():
        hosts = {t.split(":")[0] for sc in spec.get("static_configs", []) for t in sc["targets"]}
        runs_here = hosts and hosts <= services
        assert (job in bundle) == bool(runs_here or job == "fleet"), (
            f"job {job!r}: in the bundle={job in bundle}, but its targets {sorted(hosts)} "
            f"{'are' if runs_here else 'are not'} bundle services"
        )


