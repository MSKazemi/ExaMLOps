# ── nothing in the notebook is ever executed ─────────────────────────────────────────────


def test_notebook_code_is_never_executed(env, worked_example):
    """A `skip-export` cell writes a sentinel and raises SystemExit. Neither ever happens."""
    out = env / "toy_pipeline.py"
    res = _export(worked_example, out)
    assert res.exit_code == 0, res.output
    assert not (env / SENTINEL).exists()
    assert not list(env.rglob(SENTINEL))
    # Not even on the failing path: a notebook whose tagged cells are broken still runs nothing.
    broken = notebook(
        env,
        [cell(SENTINEL_CELL), cell('bad = {"name": open("x")}\n', ["dataset"])],
        stem="broken",
    )
    failed = _export(broken, env / "broken.py")
    assert failed.exit_code == 1
    assert not list(env.rglob(SENTINEL))


# ── dropping is never silent ─────────────────────────────────────────────────────────────


