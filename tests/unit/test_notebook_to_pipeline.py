"""ADR 0160 — `exa workbench export-pipeline`: tagged notebook → pipeline-DSL file.

Real extractor, real CLI runner, real `exa pipeline compile` validation path. Nothing is faked:
the generated file is loaded and compiled by the same code a hand-written pipeline file goes
through, and the "never executes the notebook" guarantee is proved with a sentinel a notebook
cell *would* write if anything ran it.
"""

