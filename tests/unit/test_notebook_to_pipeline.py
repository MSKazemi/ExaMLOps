def _export(nb: Path, out: Path, *extra: str):
    return runner.invoke(app, ["workbench", "export-pipeline", str(nb), "--out", str(out), *extra])


# ── the tag vocabulary is the IR's own, not a parallel one ───────────────────────────────


def test_step_tags_are_exactly_the_lowerable_ir_step_kinds():
    """ADR 0160 decision 1: one vocabulary. A new lowerable kind must be a decision, not drift."""
    assert STEP_TAGS == tuple(k for k, spec in STEP_KINDS.items() if spec.lowerable)
    assert set(STEP_TAGS) == {"dataset", "train", "evaluate", "promote"}
    assert KNOWN_TAGS == {*STEP_TAGS, "param", "skip-export"}
    # hpo/custom_python are known to the IR but not lowerable, so they are not extractable.
    assert not {"hpo", "custom_python"} & KNOWN_TAGS


# ── the worked example, end to end ───────────────────────────────────────────────────────


def test_worked_example_emits_the_spec_source(worked_example):
    extraction = extract_notebook(worked_example)
    assert extraction.source == EXPECTED_SOURCE
    assert extraction.name == "toy_notebook"


def test_param_values_are_inlined_not_referenced(worked_example):
    """The generated file must stand alone — it may not depend on the notebook's names."""
    source = extract_notebook(worked_example).source
    for name in ("DS_NAME", "CACHE_DIR", "RMSE_PROD"):
        assert name not in source
    assert "threshold" in source and "50.0" in source


def test_generated_file_compiles_through_the_real_cli(env, worked_example):
    out = env / "toy_pipeline.py"
    res = _export(worked_example, out)
    assert res.exit_code == 0, res.output
    assert out.is_file()
    # The same artifact a hand-written pipeline file is: `exa pipeline compile` accepts it.
    ir = env / "toy.ir.json"
    compiled = runner.invoke(app, ["pipeline", "compile", str(out), "--out", str(ir)])
    assert compiled.exit_code == 0, compiled.output
    doc = json.loads(ir.read_text())
    assert doc["name"] == "toy_notebook"
    assert [n["kind"] for n in doc["nodes"]] == ["dataset", "train", "evaluate", "promote"]
    assert doc["content_hash"].startswith("sha256:")


def test_generated_ir_equals_a_hand_written_twin(env, worked_example):
    """Golden comparison that survives reformatting: the IR hash of a hand-written twin."""
    from examlops.pipeline_dsl.loader import load_pipeline_file

    out = env / "toy_pipeline.py"
    _, generated = export_notebook(worked_example, out)
    twin = env / "twin.py"
    twin.write_text(
        "from examlops.sdk import dataset, evaluate, pipeline, promote, train\n\n\n"
        '@pipeline(name="toy_notebook")\n'
        "def toy_notebook():\n"
        '    toy = dataset("ToyDataset", backend="zenodo", cache_dir=".data_cache/toy",\n'
        '                  input_features=["x"], output_features=["y"])\n'
        '    model = train(toy, config_class="toy_config.ToyConfiguration",\n'
        '                  task_type="regression", framework="sklearn")\n'
        "    metrics = evaluate(model)\n"
        "    promote(metrics, lifecycle=[{\n"
        '        "name": "Production", "metric": "rmse", "threshold": 50.0,\n'
        '        "direction": "lower_is_better"}])\n',
        encoding="utf-8",
    )
    pdef, _ = load_pipeline_file(str(twin))
    assert generated["content_hash"] == pdef.compile()["content_hash"]


