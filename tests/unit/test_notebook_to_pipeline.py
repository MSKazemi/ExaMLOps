# ── hard failures: reject, do not guess (spec §4.2) ──────────────────────────────────────


@pytest.mark.parametrize(
    ("cells", "message"),
    [
        pytest.param(
            [cell('x = {"name": "D"}\n', ["dataset", "train"])],
            "several recognised tags",
            id="two-recognised-tags",
        ),
        pytest.param(
            [cell('x = {"name": open("f").read()}\n', ["dataset"])],
            "not extractable",
            id="a-call",
        ),
        pytest.param(
            [cell('x = {"name": f"{1}"}\n', ["dataset"])],
            "not extractable",
            id="an-f-string",
        ),
        pytest.param(
            [cell('x = {"name": n for n in []}\n', ["dataset"])],
            "dict literal",
            id="a-comprehension",
        ),
        pytest.param(
            [cell("import os\n", ["param"])],
            "must be 'NAME = <literal>'",
            id="an-import-in-a-param-cell",
        ),
        pytest.param(
            [cell('A = "x"\n', ["param"]), cell('A = "y"\n', ["param"])],
            "already declared by an earlier 'param' cell",
            id="a-duplicate-param",
        ),
        pytest.param(
            [cell('x = {"name": MISSING}\n', ["dataset"])],
            "is not declared by an earlier 'param' cell",
            id="an-unresolved-name",
        ),
        pytest.param(
            [cell('x = {"name": "D"}\ny = 1\n', ["dataset"])],
            "exactly one 'VAR = {...}' assignment",
            id="two-statements-in-a-step-cell",
        ),
        pytest.param(
            [cell('x = ["not", "a", "dict"]\n', ["dataset"])],
            "must be a dict literal",
            id="a-non-dict-step-cell",
        ),
        pytest.param(
            [
                cell('a = {"config_class": "a.B", "task_type": "r"}\n', ["train"]),
                cell('b = {"config_class": "a.B", "task_type": "r"}\n', ["train"]),
            ],
            "exactly one 'train' cell",
            id="two-train-cells",
        ),
        pytest.param(
            [
                cell('d = {"name": "D"}\n', ["dataset"]),
                cell(
                    'm = {"datasets": ["nope"], "config_class": "a.B", "task_type": "r"}\n',
                    ["train"],
                ),
            ],
            "not a tagged step cell's variable",
            id="an-unresolved-dataset-variable",
        ),
        pytest.param(
            [cell('e = {"split": "validation"}\n', ["evaluate"])],
            "needs 'model'",
            id="an-evaluate-cell-with-nothing-to-evaluate",
        ),
        pytest.param(
            [cell('train = {"config_class": "a.B", "task_type": "r"}\n', ["train"])],
            "name of the DSL helper",
            id="a-variable-shadowing-a-helper",
        ),
        pytest.param(
            [
                cell('d = {"name": "A"}\n', ["dataset"]),
                cell('d = {"name": "B"}\n', ["dataset"]),
            ],
            "already bound by an earlier tagged cell",
            id="a-duplicate-step-variable",
        ),
        pytest.param(
            [cell('x = {"name": "D"\n', ["dataset"])],
            "not valid Python",
            id="a-syntax-error",
        ),
        pytest.param(
            [cell('x = {"name": "D", "not an identifier": 1}\n', ["dataset"])],
            "is not a usable keyword",
            id="a-key-that-cannot-be-a-keyword",
        ),
    ],
)
def test_hard_failures_are_refused_with_the_offending_cell_named(env, cells, message):
    nb = notebook(env, cells, stem="bad")
    with pytest.raises(NotebookExportError) as exc:
        extract_notebook(nb)
    assert message in str(exc.value)
    res = _export(nb, env / "bad.py")
    assert res.exit_code == 1
    assert "Export failed" in res.output


def test_a_notebook_that_is_not_a_notebook_is_refused(env):
    junk = env / "not.ipynb"
    junk.write_text("{not json", encoding="utf-8")
    res = _export(junk, env / "x.py")
    assert res.exit_code == 1 and "Export failed" in res.output
    missing = _export(env / "nowhere.ipynb", env / "y.py")
    assert missing.exit_code == 1 and "not found" in missing.output


# ── CLI surface: tier and --out containment ──────────────────────────────────────────────


def _descriptor():
    return next(
        c for c in surface.build_catalog()["commands"] if c["path"] == "workbench export-pipeline"
    )


def test_the_command_is_tiered_admin():
    assert surface.TIERS["workbench export-pipeline"] == surface.ADMIN
    assert _descriptor()["tier"] == surface.ADMIN


def test_the_notebook_and_out_paths_are_contained_in_the_workspace(tmp_path):
    command = _descriptor()
    specs = {p["name"]: p for p in command["params"]}
    assert specs["notebook"].get("path") and specs["out"].get("path")
    assert specs["yaml_path"].get("path")
    inv = surface.build_argv(
        command, {"notebook": "nb/toy.ipynb", "out": "flows/toy.py"}, workspace=tmp_path
    )
    assert inv.tier == surface.ADMIN
    assert f"--out={tmp_path.resolve() / 'flows/toy.py'}" in inv.argv
    assert inv.argv[-1] == str(tmp_path.resolve() / "nb/toy.ipynb")
    assert sorted(inv.paths) == ["flows/toy.py", "nb/toy.ipynb"]


@pytest.mark.parametrize("escape", ["/etc/passwd", "../../outside.py", "~/secret.py"])
def test_a_path_outside_the_workspace_is_refused(tmp_path, escape):
    with pytest.raises(surface.SurfaceError):
        surface.build_argv(
            _descriptor(), {"notebook": "nb.ipynb", "out": escape}, workspace=tmp_path
        )


