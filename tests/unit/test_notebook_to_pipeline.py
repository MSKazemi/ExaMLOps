def test_skip_export_is_dropped_without_a_warning(env):
    nb = notebook(
        env,
        [
            cell('ds = {"name": "D"}\n', ["dataset"]),
            cell("print('deliberately left out')\n", ["skip-export"]),
            cell("print('forgotten')\n"),
        ],
    )
    extraction = extract_notebook(nb)
    assert [d.index for d in extraction.dropped] == [2]
    assert "forgotten" in extraction.dropped[0].preview


def test_a_run_that_dropped_nothing_says_so(env):
    """Absence is reported, never inferred: "nothing dropped" is a statement, not silence."""
    nb = notebook(env, [cell('ds = {"name": "D"}\n', ["dataset"])], stem="only")
    res = _export(nb, env / "only.py")
    assert res.exit_code == 0, res.output
    assert "No cells dropped" in res.output
    assert extract_notebook(nb).dropped == []


def test_an_incomplete_export_is_the_irs_verdict_not_the_extractors(env):
    """A dataset with no train step still exports (spec §4.4) — the lowering is what refuses."""
    nb = notebook(env, [cell('ds = {"name": "D"}\n', ["dataset"])], stem="partial")
    assert _export(nb, env / "partial.py").exit_code == 0
    res = _export(nb, env / "partial.py", "--yaml", str(env / "partial.yaml"))
    assert res.exit_code == 1 and "always runs a 'train' step" in res.output


def test_an_unrecognised_tag_that_looks_like_a_typo_is_warned_about(env):
    nb = notebook(env, [cell('ds = {"name": "D"}\n', ["datasets"])], stem="typo")
    extraction = extract_notebook(nb)
    assert extraction.steps == []
    assert any(
        "'datasets' is not recognised" in w and "'dataset'" in w for w in extraction.warnings
    )
    assert [d.index for d in extraction.dropped] == [0]


