runner = CliRunner()

SENTINEL = "notebook_was_executed.txt"


def cell(source: str, tags: list[str] | None = None, kind: str = "code") -> dict:
    meta: dict = {}
    if tags is not None:
        meta["tags"] = tags
    return {
        "cell_type": kind,
        "source": source,
        "metadata": meta,
        "outputs": [],
        "execution_count": None,
    }


def notebook(tmp_path: Path, cells: list[dict], stem: str = "toy_notebook") -> Path:
    path = tmp_path / f"{stem}.ipynb"
    path.write_text(
        json.dumps({"cells": cells, "metadata": {}, "nbformat": 4, "nbformat_minor": 5}),
        encoding="utf-8",
    )
    return path


